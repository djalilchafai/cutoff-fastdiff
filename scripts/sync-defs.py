#!/usr/bin/env python3
"""Generate Cutfast/Defs.lean from Challenge.lean by dropping every theorem.

The definitions used by the advertised statements must be identical in the Challenge and in
the proof development; this script keeps them textually identical.  Use `--check` in CI.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
text = (root / "Challenge.lean").read_text(encoding="utf-8")
# Split into top-level blocks separated by blank lines; drop theorem blocks (with their
# docstrings) and section headers that only introduce theorems.
blocks = re.split(r"\n\n+", text)
kept = []
for block in blocks:
    body = re.sub(r"^(open .* in\n)?/--.*?-/\n", "", block, flags=re.S)
    if body.startswith("theorem ") or body.startswith("/-! ##"):
        continue
    kept.append(block)
out = "\n\n".join(kept)
out = out.replace("# Cutoff phenomenon for fast diffusion and porous medium equations",
                  "# Definitions of the advertised statements (generated from `Challenge.lean`)", 1)
out = ("-- This file is generated by scripts/sync-defs.py from Challenge.lean; do not edit.\n"
       + out)
target = root / "Cutfast" / "Defs.lean"
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != out:
        print("Cutfast/Defs.lean is out of sync with Challenge.lean")
        sys.exit(1)
else:
    target.write_text(out, encoding="utf-8")
