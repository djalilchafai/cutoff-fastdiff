#!/usr/bin/env python3
"""Count the lines of the formalization and of the part of Mathlib it uses, into README.md and
FORMALIZATION_GUIDE.md.

"Used" means reached from the development lemmas `T'` of the advertised theorems `T`
(comparator.json) through the types and
bodies of declarations, instances included: everything the kernel checks for them. For each
library, the source lines of the reached declarations are summed (auto-generated declarations
have no source lines). The table goes between the `lines:begin` and `lines:end` markers of
each target file.

Run `lake build` first, then `python3 scripts/count-lines.py`.
"""
import json
import pathlib
import re
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
TARGETS = [ROOT / "README.md", ROOT / "FORMALIZATION_GUIDE.md"]
BEGIN, END = "<!-- lines:begin -->", "<!-- lines:end -->"

LEAN_QUERY = r"""
import Cutfast
open Lean

def body? : ConstantInfo → Option Expr
  | .thmInfo t => some t.value
  | .defnInfo v => some v.value
  | .opaqueInfo v => some v.value
  | _ => none

#eval show CoreM Unit from do
  let env ← getEnv
  let mut seen : NameSet := {}
  let mut stack : Array Name := #[NAMES]
  while h : stack.size > 0 do
    let c := stack.back
    stack := stack.pop
    if seen.contains c then continue
    seen := seen.insert c
    if let some ci := env.find? c then
      for d in ci.type.getUsedConstants ++ ((body? ci).map (·.getUsedConstants) |>.getD #[]) do
        unless seen.contains d do stack := stack.push d
  for c in seen.toList do
    let some idx := env.getModuleIdxFor? c | continue
    let m := env.header.moduleNames[idx.toNat]!
    let lines := match ← findDeclarationRanges? c with
      | some r => r.range.endPos.line - r.range.pos.line + 1
      | none => 0
    IO.println s!"USED {m} {lines}"
"""


def lines(paths) -> int:
    return sum(len(p.read_text(encoding="utf-8").splitlines()) for p in paths)


def used() -> dict[str, list[int]]:
    """Per library: [declarations, declarations with source, source lines, modules]."""
    names = json.loads((ROOT / "comparator.json").read_text(encoding="utf-8"))["theorem_names"]
    with tempfile.TemporaryDirectory() as tmp:
        query = pathlib.Path(tmp) / "Usage.lean"
        query.write_text(LEAN_QUERY.replace("NAMES", ", ".join(f"`{n}'" for n in names)),
                         encoding="utf-8")
        result = subprocess.run(["lake", "env", "lean", str(query)], cwd=ROOT,
                                capture_output=True, text=True)
    if result.returncode != 0:
        sys.exit(f"lean query failed:\n{result.stdout}\n{result.stderr}")
    stats: dict[str, list[int]] = {}
    modules: dict[str, set[str]] = {}
    for line in result.stdout.splitlines():
        m = re.fullmatch(r"USED (\S+) (\d+)", line)
        if not m:
            continue
        lib, n = m.group(1).split(".")[0], int(m.group(2))
        s = stats.setdefault(lib, [0, 0, 0, 0])
        s[0] += 1
        if n:
            s[1] += 1
            s[2] += n
            modules.setdefault(lib, set()).add(m.group(1))
    for lib, s in stats.items():
        s[3] = len(modules.get(lib, ()))
    if "Mathlib" not in stats:
        sys.exit("lean query output is incomplete")
    return stats


def table() -> str:
    own = sorted((ROOT / "Cutfast").glob("*.lean"))
    rows = [("`Cutfast/*.lean`", lines(own)),
            ("`Challenge.lean`", lines([ROOT / "Challenge.lean"])),
            ("`Solution.lean`", lines([ROOT / "Solution.lean"]))]
    total = sum(n for _, n in rows)
    mathlib = sorted((ROOT / ".lake" / "packages" / "mathlib" / "Mathlib").rglob("*.lean"))
    stats = used()
    decls, with_source, used_lines, mods = stats["Mathlib"]
    core = stats.get("Init", [0, 0, 0, 0])[2]
    out = ["| | Lines |", "|---|---:|"]
    out += [f"| {name} | {n:,} |" for name, n in rows]
    out += [f"| **This formalization** | **{total:,}** |",
            f"| Mathlib, whole library ({len(mathlib):,} files, all imported) | {lines(mathlib):,} |",
            f"| **Mathlib, used by the proofs** ({with_source:,} declarations in {mods:,} files) "
            f"| **{used_lines:,}** |"]
    return ("\n".join(out) + "\n\n"
            f"\"Used\" counts the source lines of the Mathlib declarations reached from the "
            f"{len(json.loads((ROOT / 'comparator.json').read_text())['theorem_names'])} "
            f"theorems through statements and proofs, instances included. Not counted: "
            f"{decls - with_source:,} auto-generated Mathlib declarations, and {core:,} lines of "
            f"Lean's core library. Generated by `scripts/count-lines.py`.")


def main() -> None:
    block = table()
    for target in TARGETS:
        text = target.read_text(encoding="utf-8")
        if BEGIN not in text or END not in text:
            sys.exit(f"{target.name} has no {BEGIN} ... {END} block")
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        target.write_text(f"{head}{BEGIN}\n{block}\n{END}{tail}", encoding="utf-8")
        print(f"updated {target.name}")

if __name__ == "__main__":
    main()
